import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createServer } from "vite";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";

const server = await createServer({ server: { middlewareMode: true, hmr: false }, appType: "custom" });
try {
  const { mockProjects } = await server.ssrLoadModule("/src/data/mock-projects.ts");
  const { buildManagerTaskResult, getManagerTaskIntent } = await server.ssrLoadModule("/src/lib/manager-tasks.ts");
  const { collectReportReviews, getDiligenceReportReviews, buildReportRevision, getReportVersions, getMaterialSignature, resolveReportSource, getCurrentReportCandidates, getSelectedReportSource, getReportReviewReasoningContext } = await server.ssrLoadModule("/src/lib/report-review.ts");
  const { getQuestionPathModel } = await server.ssrLoadModule("/src/data/question-paths.ts");
  const { QuestionReasoningBody } = await server.ssrLoadModule("/src/components/project/QuestionReasoningDialog.tsx");
  const { CommitteeWorkspace } = await server.ssrLoadModule("/src/components/project/CommitteeWorkspace.tsx");
  const { localizeProject } = await server.ssrLoadModule("/src/lib/content-localization.ts");
  const { reportComposerCommand, replaceComposerCommand } = await server.ssrLoadModule("/src/components/chat/ChatComposer.tsx");
  const { ReportReviewList } = await server.ssrLoadModule("/src/components/project/ReportReviewList.tsx");
  const { ProjectChangesPanel } = await server.ssrLoadModule("/src/components/project/ProjectChangesPanel.tsx");
  const { ReportVersionList } = await server.ssrLoadModule("/src/components/project/ReportVersionsSheet.tsx");
  const { ManagerReportPanel, createManagerReportDraft } = await server.ssrLoadModule("/src/components/project/ManagerReportPanel.tsx");
  const { ReportFileIcon } = await server.ssrLoadModule("/src/components/project/ReportFileIcon.tsx");
  const { LocaleProvider } = await server.ssrLoadModule("/src/lib/i18n.tsx");
  const { TooltipProvider } = await server.ssrLoadModule("/src/components/ui/tooltip.tsx");
  const { buildReportHtml } = await server.ssrLoadModule("/src/lib/report-html.ts");
  const render = (component, props) => renderToStaticMarkup(React.createElement(LocaleProvider, null, React.createElement(TooltipProvider, null, React.createElement(component, props))));
  const noop = () => {};
  const project = { ...mockProjects.find((item) => item.id === "proj-aurora"), lifecycleStage: "diligence", currentLifecycleStage: "diligence", decision: undefined };
  const file = getCurrentReportCandidates(project)[0];
  const attachments = [{ name: file.name, kind: file.kind, size: file.size }];
  const makeEntry = (id, block, createdAt = "2026-09-07T10:00:00Z", projectId = project.id) => ({ id, block, createdAt, projectId, source: "conversation" });
  const report = buildManagerTaskResult(project, "fact-check", "核对现金流", attachments)[1];
  const entry = makeEntry("check-1", report);
  assert.equal(report.sourceReport.id, file.id);
  assert.equal(getMaterialSignature(project, attachments), getMaterialSignature(project));
  assert.equal(collectReportReviews(project.id, []).length, 0, "No completed report, no pending change");
  const items = collectReportReviews(project.id, [entry]);
  assert.equal(items.length, 3);
  const baselineJson = JSON.stringify(project);
  const seeded = getDiligenceReportReviews(project, []);
  assert.equal(seeded.length, 3, "Diligence demo starts with pending changes without a fake report run");
  for (const item of seeded) {
    const context = getReportReviewReasoningContext(project, item, file.id);
    assert.equal(context.questionId, item.id);
    assert.equal(context.thesis, item.before);
    assert.equal(context.context, item.reason);
    assert.deepEqual(context.sources, item.sources);
    assert.notEqual(context.sources[0], item.sources[0], "Preserve a separate citation snapshot");
    const model = getQuestionPathModel(context);
    assert.equal(model.premise, item.after);
    const reasoning = render(QuestionReasoningBody, { context, onViewSource: noop });
    assert.ok(reasoning.includes(item.after) && reasoning.includes(item.reason));
    model.paths.forEach((path) => assert.ok(reasoning.includes(path.title)));
  }
  assert.equal(getReportReviewReasoningContext(project, { ...seeded[0], projectId: "foreign" }, file.id), undefined);
  assert.equal(getReportReviewReasoningContext(project, seeded[0], "same-name-new-id"), undefined);
  assert.equal(getReportReviewReasoningContext({ ...project, lifecycleStage: "decided" }, seeded[0], file.id), undefined);
  const changedSnapshot = { ...seeded[0], before: "新版本原表述", after: "新版本建议表述", reason: "新版本材料信号", sources: [] };
  const changedContext = getReportReviewReasoningContext(project, changedSnapshot, file.id);
  assert.equal(changedContext.questionId, `report-review:${changedSnapshot.key}`);
  assert.ok(changedContext.impact.includes(changedSnapshot.after));
  assert.deepEqual(changedContext.sources, []);
  const changedModel = getQuestionPathModel(changedContext);
  const displayedModel = [changedModel.premise, changedModel.fork, changedModel.conclusion, ...changedModel.paths.flatMap(({ title, condition, judgment, action }) => [title, condition, judgment, action])];
  assert.ok(!JSON.stringify(displayedModel).includes("425"), "Changed snapshots cannot silently borrow a prior numeric path model");
  assert.deepEqual(seeded.map((item) => item.key), items.map((item) => item.key), "Fixture keys match subsequent verification of the same baseline");
  assert.deepEqual(getDiligenceReportReviews(project, [entry]).map((item) => item.key), seeded.map((item) => item.key), "Completed work does not duplicate the fixture");
  for (const stage of ["contact", "pooled", "initiated", "decided", "signed", "funded", "post-investment"]) {
    assert.equal(getDiligenceReportReviews({ ...project, lifecycleStage: stage }, [entry]).length, 0, `No diligence review state in ${stage}`);
  }
  assert.equal(getDiligenceReportReviews({ ...project, id: "another-project" }, []).length, 0);
  assert.equal(getDiligenceReportReviews({ ...project, files: [] }, []).length, 0, "A removed original report cannot keep a fixture active");
  assert.equal(getDiligenceReportReviews({ ...project, files: project.files.map((f) => f.id === file.id ? { ...f, id: "new-report-id", name: "新版议案.pdf" } : f) }, []).length, 0);
  assert.deepEqual(getDiligenceReportReviews(localizeProject(project, "en-US"), []).map((item) => item.key), seeded.map((item) => item.key), "Language switching preserves review identity");
  const shellProps = { project, projects: mockProjects, conversations: [], reports: [], currentConversationId: null,
    conversationOpen: false, assistantContent: null, composerContent: null, reviewDecisions: {},
    onSelectProject: noop, onNewProject: noop, onOpenConversation: noop, onNewConversation: noop, onCloseConversation: noop,
    onLogout: noop, onSwitchRole: noop, onUpdateFiles: noop, onViewSource: noop, onAsk: noop, onDraftTask: noop, onReviewDecision: noop };
  assert.ok(render(CommitteeWorkspace, { ...shellProps, role: "investment-director" }).includes("待确认变更</h2><span>3 项"));
  const reviewPanel = render(ProjectChangesPanel, { project, items: seeded, decisions: {}, onDecide: noop, onViewSource: noop, onOpenReasoning: noop });
  assert.equal((reviewPanel.match(/manager-review-reasoning/g) ?? []).length, 3);
  assert.equal((reviewPanel.match(/class="manager-review-detail" hidden=""/g) ?? []).length, 3, "Reasoning links stay inside default-collapsed review details");
  const wiredShell = render(CommitteeWorkspace, { ...shellProps, role: "investment-director" });
  assert.equal((wiredShell.match(/manager-review-reasoning/g) ?? []).length, 3, "Review actions use the overview's shared dialog opener");
  assert.ok(!render(CommitteeWorkspace, { ...shellProps, role: "committee-lead" }).includes("manager-pending-changes"), "Committee never sees the manager's report changes");
  assert.ok(!render(CommitteeWorkspace, { ...shellProps, project: { ...project, lifecycleStage: "decided" }, role: "investment-director" }).includes("manager-pending-changes"));
  assert.equal(collectReportReviews(project.id, [entry, makeEntry("check-2", report, "2026-09-07T10:01:00Z")]).length, 3);
  assert.equal(collectReportReviews("another-project", [entry]).length, 0);
  for (const mode of ["investment-report", "challenge"]) {
    const block = buildManagerTaskResult(project, mode, "任务", attachments)[1];
    assert.equal(block.suggestedChanges, undefined);
    assert.equal(collectReportReviews(project.id, [makeEntry(mode, block)]).length, 0);
  }
  const pending = render(ReportReviewList, { items, decisions: {}, onDecide: noop, onViewSource: noop });
  assert.ok(pending.includes("待确认变更</h2><span>3 项") && pending.includes(">采纳</button>") && pending.includes(">忽略</button>"));
  assert.equal((pending.match(/aria-expanded="false"/g) ?? []).length, 3);
  assert.equal((pending.match(/class="manager-review-detail" hidden=""/g) ?? []).length, 3);
  assert.ok(pending.includes("查看修改") && !pending.includes("确认修改"));
  assert.ok(!pending.includes("<details open"), "Comparison is collapsed by default");
  assert.ok(pending.includes("原表述") && pending.includes("建议表述"));
  let decisions = { [items[0].key]: "accepted", [items[1].key]: "ignored" };
  const processed = render(ReportReviewList, { items, decisions, onDecide: noop, onViewSource: noop });
  assert.ok(processed.includes("待确认变更</h2><span>1 项") && processed.includes("已处理 2") && processed.includes("撤销"));
  assert.ok(processed.includes("已采纳") && processed.includes("已忽略"));
  const seededRevision = buildReportRevision(file, seeded, decisions);
  assert.equal(seededRevision.sections.length, 1);
  assert.deepEqual(seededRevision.revision.changeKeys, [seeded[0].key]);
  const allHandled = Object.fromEntries(seeded.map((item) => [item.key, "ignored"]));
  const handledHtml = render(ReportReviewList, { items: seeded, decisions: allHandled, onDecide: noop, onViewSource: noop });
  assert.ok(handledHtml.includes("待确认变更</h2><span>已处理") && handledHtml.includes("已处理 3"));
  assert.ok(!handledHtml.includes("manager-review-item-heading") && !handledHtml.includes("<details open"));
  delete allHandled[seeded[0].key];
  assert.ok(render(ReportReviewList, { items: seeded, decisions: allHandled, onDecide: noop, onViewSource: noop }).includes("待确认变更</h2><span>1 项"));
  const revision = buildReportRevision(report.sourceReport, items, decisions);
  assert.equal(revision.sections.length, 1);
  assert.ok(revision.sections[0].text.includes(items[0].after));
  assert.deepEqual(revision.revision.changeKeys, [items[0].key]);
  assert.equal(report.suggestedChanges[0].before, items[0].before, "Original report must not be mutated");
  assert.ok(buildReportHtml(revision).includes(items[0].after));

  const newProject = { ...project, files: [...project.files, { id: "supplement", name: "客户明细新增.xlsx", kind: "excel", size: "3MB", category: "财务尽调", status: "indexed", uploadedAt: "2026-09-07" }] };
  const nextReport = buildManagerTaskResult(newProject, "fact-check", "更新核验", attachments)[1];
  const nextEntry = makeEntry("check-new-material", nextReport, "2026-09-07T11:00:00Z");
  const latest = collectReportReviews(project.id, [entry, nextEntry]);
  const all = collectReportReviews(project.id, [entry, nextEntry], true);
  assert.equal(latest.length, 3, "Superseded batches must not duplicate pending cards");
  assert.equal(all.length, 6, "Retain prior decisions for revision history");
  assert.deepEqual(getDiligenceReportReviews(newProject, []).map((item) => item.key), seeded.map((item) => item.key), "Uploading new material alone cannot reset processed fixture keys");
  assert.deepEqual(getDiligenceReportReviews(newProject, [nextEntry]).map((item) => item.key), latest.map((item) => item.key));
  assert.equal(getDiligenceReportReviews(newProject, [nextEntry], true).length, 6, "Keep prior acceptance available for revision history");
  assert.ok(latest.every((item) => !decisions[item.key]));
  assert.equal(buildReportRevision(report.sourceReport, all, decisions).sections[0].text, revision.sections[0].text, "New pending suggestions do not undo prior acceptance");
  decisions[latest[0].key] = "ignored";
  assert.equal(buildReportRevision(report.sourceReport, all, decisions).sections[0].text, revision.sections[0].text, "Ignoring a new suggestion retains prior accepted text");
  const restored = buildReportRevision(report.sourceReport, all, { [items[1].key]: "ignored" });
  assert.equal(restored.revision.changeKeys.length, 0);
  assert.ok(restored.sections[0].text.includes("以原报告为准"));

  const upload = { name: "新版投决议案.pdf", size: "5MB", kind: "pdf" };
  const uploadReport = buildManagerTaskResult(project, "fact-check", "核验新上传报告", [upload])[1];
  const uploadEntry = makeEntry("uploaded", uploadReport);
  assert.equal(uploadReport.sourceReport.origin, "attachment");
  assert.ok(getCurrentReportCandidates(project, [uploadEntry]).some((candidate) => candidate.id === uploadReport.sourceReport.id));
  const preferred = getSelectedReportSource(project, [uploadEntry], uploadReport.sourceReport.id);
  assert.equal(resolveReportSource(project, [], preferred).id, uploadReport.sourceReport.id);
  assert.equal(buildManagerTaskResult(project, "fact-check", "@交叉验证", [], preferred)[1].sourceReport.id, uploadReport.sourceReport.id);
  assert.equal(resolveReportSource(project, attachments, preferred).id, file.id, "Explicit report attachment overrides current selection");
  const primaryDraft = makeEntry("generated", buildManagerTaskResult(project, "investment-report", "生成报告", attachments)[1]);
  const revisionEntry = makeEntry("revision", revision, "2026-09-07T12:00:00Z");
  const wrongProject = makeEntry("foreign", primaryDraft.block, undefined, "another-project");
  assert.deepEqual(getReportVersions(project, file.id, [entry, primaryDraft, revisionEntry, uploadEntry, wrongProject]).map((entry) => entry.id), ["revision", "generated"]);
  const versions = render(ReportVersionList, { project, selectedId: file.id, reports: [entry, primaryDraft, revisionEntry], onSelectSource: noop, onOpenReport: noop });
  assert.ok(versions.includes("修订草稿") && versions.includes("生成草稿"));
  assert.ok(!versions.includes("check-1") && !versions.includes("核对现金流"));
  const icon = render(ReportFileIcon, { name: "原报告.pdf" });
  assert.ok(icon.includes("file-pdf") && icon.includes("#d9363e"));
  const panel = render(ManagerReportPanel, { project, draft: { ...createManagerReportDraft(project), selectedId: uploadReport.sourceReport.id }, reports: [uploadEntry], onDraftChange: noop, onDraftTask: noop, onViewSource: noop, onOpenKnowledge: noop, onOpenReport: noop });
  assert.ok(panel.includes(upload.name) && panel.includes("历史版本"));
  assert.ok(!panel.includes("已有报告引用"), "Do not attribute old excerpts to a newly uploaded version");
  const otherSourcePanel = render(ManagerReportPanel, { project, draft: { ...createManagerReportDraft(project), selectedId: uploadReport.sourceReport.id }, reports: [uploadEntry], reviewItems: seeded, onReviewDecision: noop, onDraftChange: noop, onDraftTask: noop, onViewSource: noop });
  assert.ok(!otherSourcePanel.includes("manager-pending-changes"), "Do not attach the demo's changes to a new report");
  const readOnlyPanel = render(ManagerReportPanel, { project, draft: createManagerReportDraft(project), reviewItems: seeded, readOnly: true, onReviewDecision: noop, onDraftChange: noop, onDraftTask: noop, onViewSource: noop });
  assert.ok(!readOnlyPanel.includes("manager-pending-changes"));
  assert.equal(JSON.stringify(project), baselineJson, "Reviewing never mutates the original project or report");
  const command = reportComposerCommand("zh-CN", "investment-director");
  assert.equal(command, "@生成报告");
  assert.equal(getManagerTaskIntent(replaceComposerCommand("@投资分析 核对质询", command)), "investment-report");
  assert.equal(replaceComposerCommand("模拟投委会：核对成本", command), "@生成报告 核对成本");
  assert.equal(replaceComposerCommand("@生成报告 原要求", "@交叉验证"), "@交叉验证 原要求");
  const css = await readFile(new URL("../src/components/project/manager-workspace.css", import.meta.url), "utf8");
  assert.ok(css.includes("width: min(900px, calc(100% - 48px))") && css.includes("box-shadow: 0 8px 32px"));
  assert.ok(css.includes("var(--manager-composer-height"), "Floating composer reserves reading space");
  const app = await readFile(new URL("../src/App.tsx", import.meta.url), "utf8");
  const overview = await readFile(new URL("../src/components/project/CommitteeOverview.tsx", import.meta.url), "utf8");
  assert.ok(overview.includes('beforeQuestions(openReasoning)') && overview.includes('returnFocusTo={reasoningTrigger.current}'));
  assert.ok(overview.includes('[project.lifecycleStage, reasoningScopeKey]'), "Report and stage changes close stale reasoning");
  const panelSource = await readFile(new URL("../src/components/project/ProjectChangesPanel.tsx", import.meta.url), "utf8");
  assert.ok(panelSource.includes('onOpenReasoning(context, event.currentTarget)'), "Returning from reasoning targets the originating review action");
  assert.ok(app.includes("nextPrompt.reportSource") && app.includes("reportSource: activeReportSourceFor(projectId)"));
  assert.ok(app.includes('authSession?.role !== "investment-director" || project?.lifecycleStage !== "diligence"'));
  assert.ok(app.includes("getDiligenceReportReviews(project, projectReports, true)"), "UI and handling resolve the same seeded keys");
  console.log("PASS: diligence manager's preloaded review state; role/stage/report isolation; stable locale/material identity; completed-work dedupe; adopt/ignore/undo and revision history; compact collapsed comparisons; floating composer and report contracts.");
} finally { await server.close(); }
