export function getQuestionPathModel(question: CoreQuestion | QuestionContext): QuestionPathModel {
  const id = "questionId" in question ? question.questionId : question.id;
  if ("stage" in question && question.stage === "decided") return {
    premise: "以已确认的有效决议为基准；材料提交、核验完成与授权批准分别处理。当前仅有投决情景演示。",
    fork: "新增依据满足批准要求，还是出现了需要重新判断的实质差异？",
    conclusion: `当前应先核对决议要求及证明材料，不能把提醒处理等同于条件已完成。${question.impact}`,
    paths: [
      { id: `${id}-verified`, title: "证据满足原要求", condition: question.neededEvidence, judgment: "由授权人员核验后记录完成，不自动授权出资。", action: "保留材料、核验人和核验结论。" },
      { id: `${id}-supplement`, title: "材料尚不足", condition: "只有部分证明，或文件口径仍有差异。", judgment: "原条件继续有效。", action: "补证或修改文件后再次提交复核。" },
      { id: `${id}-change`, title: "原决策前提发生变化", condition: "新依据实质改变获批方案的基础或交易边界。", judgment: "需按机构权限补充判断，不能自行豁免。", action: "整理原批准内容、新变化及影响，提交有权限人员审议。" },
    ],
  };
  const fallback: PathDefinition = [
    "先区分已知材料、待核实判断与条件假设，不把缺失证据视作已经通过。",
    question.question,
    `当前应结合材料确认这一事项是否改变投资判断。${question.impact}`,
    ["关键证据支持主张", question.neededEvidence, "在证据覆盖范围内复核原投资主张。", "保存来源与核查口径。"],
    ["证据仅部分支持", "部分事实可验证，仍存在与主张有关的缺口。", "保留有条件判断，明确未决范围。", "补齐关键缺口后再确认。"],
    ["证据不支持主张", "必要证据缺失，或出现与主张矛盾的材料。", question.impact, "重新审查对应投资主张。"],
  ];
  const [premise, fork, conclusion, ...paths] = definitions[id] ?? fallback;
  return { premise, fork, conclusion, paths: paths.map(([title, condition, judgment, action], index) => ({id: `${id}-${index}`, title, condition, judgment, action})) };
}
